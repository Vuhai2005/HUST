const renderSearchResults = (query = "") => {
  const resultsBox = $("[data-search-results]");
  if (!resultsBox) return;

  const cleanQuery = normalizeText(query.trim());

  if (!cleanQuery) {
    resultsBox.innerHTML = `
      <div class="search-result">
        <strong>${escapeHTML(t("search.emptyTitle"))}</strong>
        <span>${escapeHTML(t("search.emptyText"))}</span>
      </div>
    `;
    return;
  }

  const results = buildSearchIndex()
    .filter((item) => normalizeText(`${item.type} ${item.title} ${item.summary}`).includes(cleanQuery))
    .slice(0, 9);

  resultsBox.innerHTML = results.length
    ? results
        .map(
          (item) => `
            <a class="search-result" href="${escapeHTML(item.target)}" data-search-result>
              <strong>${escapeHTML(item.title)}</strong>
              <span>${escapeHTML(item.type)} - ${escapeHTML(item.summary)}</span>
            </a>
          `,
        )
        .join("")
    : `
      <div class="search-result">
        <strong>${escapeHTML(t("search.noResultTitle"))}</strong>
        <span>${escapeHTML(t("search.noResultText"))}</span>
      </div>
    `;
};

