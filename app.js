document.addEventListener("DOMContentLoaded", () => {
  if (!["vi", "en"].includes(currentLanguage)) {
    currentLanguage = "vi";
  }

  const savedTheme = localStorage.getItem("hust-portal-theme");
  if (savedTheme) {
    document.documentElement.dataset.theme = savedTheme;
  }

  rerenderAll();
  setupScrollEffects();
  setupReveal();
  animateCounters();
  window.setInterval(updateClock, 60000);

  $$("[data-lang-toggle]").forEach((button) => {
    button.addEventListener("click", () => {
      const nextLanguage = button.dataset.langToggle;
      if (!nextLanguage || nextLanguage === currentLanguage) return;

      currentLanguage = nextLanguage;
      localStorage.setItem("hust-portal-language", currentLanguage);
      rerenderAll();
      showToast(currentLanguage === "vi" ? t("toast.langVi") : t("toast.langEn"));
    });
  });

  $("[data-theme-toggle]")?.addEventListener("click", () => {
    const root = document.documentElement;
    const nextTheme = root.dataset.theme === "dark" ? "light" : "dark";
    root.dataset.theme = nextTheme;
    localStorage.setItem("hust-portal-theme", nextTheme);
    showToast(nextTheme === "dark" ? t("toast.dark") : t("toast.light"));
  });

  const menuButton = $("[data-menu-toggle]");
  menuButton?.addEventListener("click", () => {
    const isOpen = document.body.classList.toggle("nav-open");
    menuButton.setAttribute("aria-expanded", String(isOpen));
    menuButton.setAttribute("aria-label", isOpen ? t("actions.closeMenu") : t("actions.openMenu"));
  });

  $$("[data-dropdown-toggle]").forEach((button) => {
    button.addEventListener("click", () => {
      const group = button.closest(".nav-group");
      const isOpen = group?.classList.toggle("is-open") ?? false;
      button.setAttribute("aria-expanded", String(isOpen));
    });
  });

  $$("[data-nav] a").forEach((link) => {
    link.addEventListener("click", () => {
      document.body.classList.remove("nav-open");
      menuButton?.setAttribute("aria-expanded", "false");
    });
  });

  $$("[data-timeline-filter]").forEach((button) => {
    button.addEventListener("click", () => {
      const filter = button.dataset.timelineFilter;
      selectTimelineFilter(filter);
      showToast(t("toast.filter", { value: t(`filters.${filter}`) }));
    });
  });

  $$("[data-filter-shortcut]").forEach((link) => {
    link.addEventListener("click", () => {
      const filter = link.dataset.filterShortcut;
      selectTimelineFilter(filter);
    });
  });

  $$("[data-unit-filter]").forEach((button) => {
    button.addEventListener("click", () => {
      const filter = button.dataset.unitFilter;
      selectUnitFilter(filter);
    });
  });

  $$("[data-program-tab]").forEach((button) => {
    button.addEventListener("click", () => {
      selectProgramTab(button.dataset.programTab);
    });
  });

  $$("[data-program-shortcut]").forEach((link) => {
    link.addEventListener("click", () => {
      selectProgramTab(link.dataset.programShortcut);
    });
  });

  const searchDialog = $("[data-search-dialog]");
  const dialogSearch = $("[data-dialog-search]");
  const liveSearch = $("[data-live-search]");

  const openSearch = () => {
    openDialog(searchDialog);
    const query = liveSearch?.value ?? "";
    if (!dialogSearch) return;

    dialogSearch.value = query;
    renderSearchResults(query);
    window.setTimeout(() => dialogSearch.focus(), 80);
  };

  $$("[data-search-open]").forEach((button) => button.addEventListener("click", openSearch));

  liveSearch?.addEventListener("keydown", (event) => {
    if (event.key !== "Enter") return;
    event.preventDefault();
    openSearch();
  });

  dialogSearch?.addEventListener("input", (event) => {
    renderSearchResults(event.target.value);
  });

  $("[data-search-results]")?.addEventListener("click", (event) => {
    if (event.target.closest("[data-search-result]")) {
      closeDialog(searchDialog);
    }
  });

  document.addEventListener("click", (event) => {
    const serviceButton = event.target.closest("[data-service]");
    if (!serviceButton) return;

    const serviceId = serviceButton.dataset.service;
    if (serviceId === "timeline") {
      showToast(t("toast.notify"));
      return;
    }

    const service = serviceItems.find((item) => item.id === serviceId);
    const label = service ? localize(service).title : serviceId;
    showToast(t("toast.service", { value: label }));
  });

  $("[data-contact-form]")?.addEventListener("submit", (event) => {
    event.preventDefault();
    const form = event.currentTarget;
    const data = new FormData(form);
    const name = data.get("name") || t("contact.title");
    form.reset();
    showToast(t("toast.contact", { value: name }));
  });
});
