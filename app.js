const escapeHTML = (value) =>
  String(value).replace(/[&<>"']/g, (character) => {
    const replacements = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#039;",
    };
    return replacements[character];
  });

const getNestedValue = (source, path) =>
  path.split(".").reduce((current, key) => (current && current[key] !== undefined ? current[key] : undefined), source);

const t = (path, replacements = {}) => {
  const dictionary = dictionaries[currentLanguage] || dictionaries.vi;
  const fallback = dictionaries.vi;
  const value = getNestedValue(dictionary, path) ?? getNestedValue(fallback, path) ?? path;

  return Object.entries(replacements).reduce(
    (text, [key, replacement]) => text.replaceAll(`{${key}}`, replacement),
    value,
  );
};

const localize = (item) => item[currentLanguage] || item.vi;

const locale = () => (currentLanguage === "vi" ? "vi-VN" : "en-US");

const normalizeText = (value) =>
  String(value)
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .replace(/đ/g, "d");

const formatDate = (isoDate, options = {}) =>
  new Intl.DateTimeFormat(locale(), {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    ...options,
  }).format(new Date(`${isoDate}T00:00:00`));

